export function typeArticle(code: string): string | null {
  return ARTICLES[code.trim().toUpperCase()] ?? null
}

/** Lead image of the type's Wikipedia article, or null if none. */
export async function fetchTypePhoto(
  code: string,
  userAgent: string,
): Promise<PhotoBody | null> {
  const article = typeArticle(code)
  if (!article) return null
  const res = await fetch(
    `https://en.wikipedia.org/api/rest_v1/page/summary/${encodeURIComponent(article)}`,
    { headers: { 'User-Agent': userAgent } },
  )
  if (!res.ok) return null
  const data = (await res.json()) as {
    thumbnail?: { source?: string }
    content_urls?: { desktop?: { page?: string } }
  }
  const src = data.thumbnail?.source
  if (!src) return null
  return {
    src,
    link: data.content_urls?.desktop?.page || `https://en.wikipedia.org/wiki/${article}`,
    photographer: 'Wikipedia',
  }
}
